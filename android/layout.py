# -*- coding: utf-8 -*-
"""
layout.py — вертикально или горизонтально, и что из этого следует.

Приложение до сих пор жило только в портрете. Это разумно для леса — телефон
держат одной рукой, — но не для всего: карту похода на боку видно вдвое
шире, а на планшете портретная раскладка растягивает шесть кнопок на полэкрана
и оставляет карту в марке.

Правило одно: горизонтальным считается экран шире, чем выше. Порог не
подгоняется под конкретные аппараты — их слишком много, а полоса вокруг
единицы всё равно ничья: квадратный экран одинаково плох в обеих раскладках.

Ширина сама по себе тоже важна. Обычный телефон на боку — это около 640
независимых точек, и две колонки выходят по 370 и 270: в такие график и
список дней помещаются. А вот старый аппарат с шириной 320 даёт на боку
560, то есть колонки по 320 и 240, и список дней в правой уже ломается по
словам. Поэтому есть порог: ниже него остаётся привычный столбец, просто
более низкий.
"""

from __future__ import annotations

#: Ниже этой ширины (в независимых точках) вторая колонка вредна: правая
#: становится уже 250 точек, и подписи кнопок в ней начинают ломаться.
MIN_WIDTH_DP = 600.0

#: Доля ширины под левую колонку. Слева то, на что смотрят (карта, график),
#: справа — то, что нажимают: под правую руку, которой держат телефон.
LEFT_SHARE = 0.58


def is_landscape(width: float, height: float) -> bool:
    return bool(width) and bool(height) and width > height


def two_columns(width: float, height: float, dp_scale: float = 1.0) -> bool:
    """Стоит ли раскладывать экран в две колонки."""
    if not is_landscape(width, height):
        return False
    return width / max(dp_scale, 0.01) >= MIN_WIDTH_DP


def split(width: float, share: float = LEFT_SHARE) -> tuple:
    """Ширины колонок: (левая, правая)."""
    left = max(0.0, min(1.0, share))
    return left, 1.0 - left


def changed(before: tuple, after: tuple, dp_scale: float = 1.0) -> bool:
    """Изменилась ли раскладка при изменении размера окна.

    Пересобирать экран на каждый пиксель нельзя: Android присылает десятки
    событий за один поворот, а пересборка — это заново созданные виджеты и
    моргание. Отвечать надо только на смену самой раскладки.
    """
    return (two_columns(*before, dp_scale=dp_scale)
            != two_columns(*after, dp_scale=dp_scale))
