# -*- coding: utf-8 -*-
"""
markup.py — экранирование текста, который попадает в разметку Kivy.

Kivy разбирает в подписях теги вида [b], [color=…], [size=…]. Обычно чужая
квадратная скобка проходит насквозь: «Ельник [север]» так и рисуется. Но не
всякая — [size=что-угодно] разбирается всерьёз, и на нечисловом значении
Label падает с ValueError прямо при отрисовке.

Само по себе это редкость: место надо назвать «[size=x]». Опасен другой
случай — окно аварии. В него уходит текст исключения, а он бывает каким
угодно, включая repr со скобками. Окно, которое падает, показывая ошибку,
не оставляет человеку вообще ничего: ни причины, ни возможности её снять.

Поэтому всё, что пришло не от программиста — название места, заметка,
трассировка, ответ сервера, — проходит через esc(). Свои теги при этом
пишутся вокруг уже экранированного текста и работают как раньше.

Сущности &bl; и &br; — штатный способ Kivy написать скобку буквально.
"""

from __future__ import annotations


def esc(text) -> str:
    """Текст, безопасный внутри разметки Kivy.

    Амперсанд экранируется первым, иначе следом добавленные &bl; сами
    оказались бы испорчены.
    """
    return (str(text)
            .replace("&", "&amp;")
            .replace("[", "&bl;")
            .replace("]", "&br;"))
