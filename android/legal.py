TOUCH = dp(48)


def _wrapping(label):
    label.size_hint_y = None
    label.halign = "left"
    label.valign = "top"
    label.bind(width=lambda w, x: setattr(w, "text_size", (x, None)),
              texture_size=lambda w, t: setattr(w, "height", t[1]))
    return label


def _show(title, text):
    """Одно и то же окно для privacy и terms — заголовок и текст разные."""
    box = BoxLayout(orientation="vertical", padding=dp(10), spacing=dp(8))

    sv = ScrollView()
    label = _wrapping(Label(text=text, font_size=sp(12), color=INK))
    sv.add_widget(label)
    box.add_widget(sv)

    popup = Popup(title=title, content=box, size_hint=(0.94, 0.9),
                  title_size=sp(15), separator_color=ACCENT)

    close = Button(text="Закрыть", size_hint_y=None, height=TOUCH,
                   font_size=sp(14), background_normal="",
                   background_color=SOFT, color=INK)
    close.bind(on_release=lambda *_: popup.dismiss())
    box.add_widget(close)

    uikit.open_soft(popup)
    return popup


def show_privacy():
    return _show("Конфиденциальность", PRIVACY_TEXT.strip())


def show_terms():
    return _show("Условия использования", TERMS_TEXT.strip())
