# -*- coding: utf-8 -*-
"""
licensecode.py — код разблокировки без сервера.

Зачем этот путь существует рядом с RuStore-биллингом. Пока покупка через
RuStore не обкатана на реальном телефоне (см. billing.py — там честно
сказано, чего не хватает), человеку всё равно нужен способ получить версию
без рекламы сегодня, а не после того, как биллинг доведут до ума. Тот же
путь остаётся и подстраховкой на потом: если RuStore-покупка у кого-то не
проходит, у вас должен быть способ выдать доступ руками, не трогая код.

Как это работает. У каждой установки свой код устройства — короткая строка,
которую видно на экране покупки. Человек переводит 300 ₽ по СБП (реквизиты
уже есть в donate.py) и присылает вам код устройства. Вы считаете код
разблокировки локальным скриптом (см. `tools/make_unlock_code.py`) и
отправляете его человеку; он вводит код в приложение.

Это НЕ защита от списывания, и приложение говорит об этом человеку прямо,
а не молчит. Секретный ключ ниже уезжает в APK вместе со всем остальным
кодом, а Python из APK достаётся легче, чем Java из обычного приложения —
кто станет разбирать архив, найдёт SECRET и сможет посчитать код себе сам.
Это тот же порядок вещей, что у любого маленького приложения без сервера:
код не про технику, а про то, что платить за труд — это по-честному, и его
не грех попросить. Настоящую защиту даёт только RuStore-биллинг, когда его
доведут.

Формат кода — 8 символов из алфавита без похожих букв (0/O, 1/I) и с
дефисом посередине для чтения на глаз: «7K4M-9PQR». Меньше восьми — код
подбирают перебором за разумное время; больше — его тяжело продиктовать
по телефону, а именно так его обычно и передают.
"""

from __future__ import annotations

import hashlib
import hmac
import re

import prefs

# Меняете один раз, перед первой публикацией — и никогда потом: смена ключа
# делает недействительными все код, которые вы уже разослали. Держите его
# только у себя, не в переписке с покупателями.
#
# СГЕНЕРИРОВАТЬ СВОЙ: python3 -c "import secrets; print(secrets.token_hex(16))"
SECRET = "0000000000000000000000000000000000"

ALPHABET = "23456789ABCDEFGHJKLMNPQRSTUVWXYZ"        # без 0/O и 1/I
CODE_LEN = 8


def device_code() -> str:
    """Код этого экземпляра приложения. Показывается на экране покупки.

    Не случайный — выводится из первого запуска (см. `_seed()`), поэтому
    остаётся одним и тем же, пока человек не переустановит приложение или
    не сотрёт данные. Так код разблокировки, однажды выданный, продолжает
    подходить после обновления версии.
    """
    seed = prefs.get("license_seed", "")
    if not seed:
        import os
        seed = os.urandom(16).hex()
        prefs.save(license_seed=seed)
    return _format(_digest(seed, "device"))


def unlock_code_for(device: str) -> str:
    """Код разблокировки для присланного device_code. Запускается У ВАС,
    не в приложении — см. tools/make_unlock_code.py."""
    return _format(_digest(_normalize(device), "unlock"))


def verify(entered: str) -> bool:
    """Проверяет код, который человек ввёл в приложение."""
    ожидаемый = unlock_code_for(device_code())
    return hmac.compare_digest(_normalize(entered), _normalize(ожидаемый))


def _digest(text: str, salt: str) -> bytes:
    return hmac.new(SECRET.encode("utf-8"), f"{salt}:{text}".encode("utf-8"),
                    hashlib.sha256).digest()


def _format(raw: bytes) -> str:
    n = int.from_bytes(raw[:8], "big")
    chars = []
    for _ in range(CODE_LEN):
        n, rem = divmod(n, len(ALPHABET))
        chars.append(ALPHABET[rem])
    code = "".join(chars)
    return code[:4] + "-" + code[4:]


def _normalize(code: str) -> str:
    """К одному виду перед сравнением: без пробелов и дефисов, заглавными.

    Человек присылает код откуда угодно — из СМС, из голосового в текст,
    иногда переписывает от руки, — и различия в пробелах не должны стоить
    ему повторного письма.
    """
    return re.sub(r"[\s-]", "", code.strip().upper())
