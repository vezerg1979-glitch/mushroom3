# -*- coding: utf-8 -*-
"""
premium.py — куплено ли «без рекламы», и ничего больше.

Модуль намеренно тупой: одно битовое состояние в prefs, читаемое отовсюду,
откуда решают, показывать рекламу или нет. Ни RuStore, ни сеть, ни jnius он
не трогает — это забота billing.py. Здесь же то, что должно работать
одинаково что на телефоне, что при прогоне тестов на компьютере: сама
проверка «куплено ли» не имеет права зависеть от того, откуда пришло
подтверждение покупки.

Источник записывается вместе с флагом не для показа человеку, а для разбора
жалоб через полгода: «rustore» — обычная покупка, «manual» — ручная сверка
по СБП-переводу для тех случаев, когда RuStore-биллинг недоступен или дал
сбой. Оба источника дают одинаковое право — рекламы нет, — но если человек
напишет «платил, а реклама осталась», разница между «покупка не прошла» и
«прошла, но не считалась» видна сразу.
"""

from __future__ import annotations

import time

import prefs


def is_premium() -> bool:
    return bool(prefs.get("premium", False))


def unlock(source: str = "rustore", when: float = None) -> None:
    """Отмечает покупку. source — откуда пришло подтверждение."""
    prefs.save(premium=True, premium_source=source,
              premium_at=when or time.time())


def info() -> dict:
    """Для экрана диагностики и для карточки в «Приём и сервис».

    Возвращает то же самое, что записано, а не пересчитывает заново —
    здесь важна история, а не текущий пересчёт.
    """
    return {
        "premium": is_premium(),
        "source": prefs.get("premium_source", ""),
        "at": prefs.get("premium_at", 0.0),
    }
