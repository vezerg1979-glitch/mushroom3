MIN_CONTRAST = 4.5
MIN_CONTRAST_LARGE = 3.0


def _channel(value: int) -> float:
    c = value / 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def luminance(color: str) -> float:
    """Относительная яркость цвета #RRGGBB по WCAG."""
    h = color.lstrip("#")
    if len(h) != 6:
        raise ValueError(f"цвет должен быть в виде #RRGGBB, получено {color!r}")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return 0.2126 * _channel(r) + 0.7152 * _channel(g) + 0.0722 * _channel(b)


def contrast(fg: str, bg: str) -> float:
    """Контраст пары цветов: 1.0 — не видно, 21.0 — чёрное на белом."""
    a, b = luminance(fg), luminance(bg)
    lo, hi = (a, b) if a < b else (b, a)
    return (hi + 0.05) / (lo + 0.05)


def level_colors(value: float):
    """Плашка и цвет цифры для значения индекса."""
    for threshold, bg, fg in LEVELS:
        if value >= threshold:
            return bg, fg
    return LEVELS[-1][1], LEVELS[-1][2]
