_current = "день"


def use(name: str) -> str:
    """Переключает набор цветов. Возвращает применённое имя.

    Значения раскладываются в те же имена модуля (BG, INK, ...), которыми
    пользуется весь код: так переключение темы не требует править каждое
    обращение к цвету, а модулям остаётся только перечитать значения.
    """
    if name not in THEMES:
        raise ValueError(f"нет такой темы: {name!r}; "
                         f"есть: {', '.join(THEMES)}")
    global LEVELS, SPECIES, RAIN, _current
    colors, levels, species, rain = THEMES[name]
    globals().update(colors)
    LEVELS = levels
    SPECIES = species
    RAIN = rain
    _current = name
    return name


def current() -> str:
    return _current


