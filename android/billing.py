# -*- coding: utf-8 -*-
"""
billing.py — покупка «без рекламы» через RuStore.

Читайте это до того, как понадеётесь на модуль в бою.

RuStore Billing SDK написан на Kotlin, и часть его публичного API — это
suspend-функции (корутины), а не обычные Java-методы. У обычных методов
jnius вызывает Java-сигнатуру и получает результат синхронно; у
Kotlin-корутины ЕСТЬ Java-сигнатура (компилятор добавляет служебный
параметр Continuation), но вызвать её напрямую через jnius — значит вручную
собрать этот Continuation и разобрать корутинный протокол. Это не невозможно,
но и не то, что можно написать вслепую и считать готовым: сама попытка
собрать это без реального устройства, без RuStore на нём и без вашего
продукта, заведённого в консоли RuStore, гарантированно даст код, который
либо не соберётся, либо соберётся и упадёт при первом вызове.

Поэтому здесь — то, что можно написать заранее честно: обёртка с понятным
контрактом (is_available, purchase, restore), которая на сегодня всегда
отвечает «недоступно» и не делает вида, что покупка работает. Экран покупки
(premium_screen.py) это учитывает и держит РАБОЧИЙ путь — код разблокировки
по СБП (licensecode.py) — не запасным, а основным, пока здесь не появится
настоящий вызов.

Что нужно, чтобы довести до конца:
  1. Товар «без рекламы» заведён в консоли RuStore, известен его product_id.
  2. RuStore Billing SDK подключён как gradle-зависимость: нужен p4a-рецепт
     или ручная правка сборки — просто requirements = ...,rustore-billing
     не сработает, это не pip-пакет.
  3. Либо в самом SDK есть Java-дружественная обёртка над корутинами (у
     некоторых версий есть), либо придётся написать небольшой класс на
     Kotlin/Java, который сам дожидается результата и отдаёт его через
     обычный колбэк — и уже его вызывать через jnius.
  4. Всё это проверяется на живом телефоне с установленным RuStore и
     тестовой покупкой из их же песочницы — иначе о работоспособности
     нельзя судить вообще.
"""

from __future__ import annotations

import premium

#: Заполнить после регистрации товара в консоли RuStore.
PRODUCT_ID = "no_ads_300"

#: Почему покупка не удалась в последний раз. Та же идея, что в ads.py и
#: notify.py: молчаливый сбой неотличим от «человек ещё не нажал купить».
last_error = "RuStore-биллинг не подключён: нужна нативная сборка (см. docstring)"


def is_available() -> bool:
    """Готов ли настоящий путь покупки. Сейчас — нет, и это не баг.

    Экран покупки проверяет это до того, как предложить кнопку «Купить
    через RuStore»: если модуль ещё не доведён, кнопки попросту не будет,
    а не будет висеть неработающей.
    """
    return False


def purchase(on_done) -> bool:
    """Запускает покупку. on_done(ok, error) вызывается по завершении.

    Возвращает False сразу же, пока is_available() — False: не пытается
    изобразить попытку там, где заведомо нечего вызывать.
    """
    if not is_available():
        on_done(False, last_error)
        return False
    # Сюда — настоящий вызов RuStore Billing после того, как пункты из
    # docstring выше выполнены.
    on_done(False, "не реализовано")
    return False


def restore(on_done) -> bool:
    """Восстановление покупки на новом устройстве — тот же путь, что purchase."""
    if not is_available():
        on_done(False, last_error)
        return False
    on_done(False, "не реализовано")
    return False
