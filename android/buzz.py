# -*- coding: utf-8 -*-
"""
buzz.py — короткий виброотклик на важные нажатия.

Зачем. Метку ставят, не глядя на экран: телефон в одной руке, нож и корзина
в другой, солнце в стекле. Единственное подтверждение, что «Нашёл!» сработало,
сейчас — надпись мелким шрифтом, которую в этот момент никто не читает.
Короткий толчок в ладонь говорит то же самое и доходит наверняка.

Отклик намеренно скупой: старт и пауза записи, поставленная метка, отменённая
метка. Вибрация на каждое касание раздражает и съедает батарею, а батарея в
лесу — это ещё и навигация обратно к машине.

Модуль ничего не требует: нет вибромотора, нет plyer, отказано в доступе —
функции просто ничего не делают. Молча: сообщение «вибрация недоступна» не
несёт человеку в лесу никакой пользы.
"""

from __future__ import annotations

# Сломанный или отсутствующий мотор проверяется один раз. Без этого каждое
# нажатие уходило бы в исключение внутри plyer — на слабом телефоне это
# заметная задержка ровно в тот момент, когда человек ждёт отклика.
_broken = False

#: Длительность толчков, секунды. Подобраны так, чтобы отличаться на ощупь
#: через карман куртки: «сделано» — точка, «отменено» — тире.
TAP = 0.03
LONG = 0.09


def _vibrate(seconds: float) -> bool:
    global _broken
    if _broken or seconds <= 0:
        return False
    try:
        from plyer import vibrator
        vibrator.vibrate(seconds)
        return True
    except Exception:                                             # noqa: BLE001
        _broken = True
        return False


def tap() -> bool:
    """Короткий толчок: действие принято (метка, старт)."""
    return _vibrate(TAP)


def long() -> bool:
    """Толчок подлиннее: что-то отменено или закончено."""
    return _vibrate(LONG)


def reset() -> None:
    """Забыть отказ мотора. Нужен тестам и переустановке разрешений."""
    global _broken
    _broken = False
